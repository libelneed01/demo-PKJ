export const rp = (n) => "Rp " + Math.round(n || 0).toLocaleString("id-ID");
export const rpJt = (n) => (n / 1e6).toLocaleString("id-ID", { maximumFractionDigits: 1 }) + " jt";
export const fmtDate = (s) => (s ? new Date(s).toLocaleDateString("id-ID", { day: "2-digit", month: "short", year: "numeric" }) : "-");
export const fmtTime = (s) => (s ? new Date(s).toLocaleTimeString("id-ID", { hour: "2-digit", minute: "2-digit" }).replace(".", ":") : "-");
export const fmtDT = (s) => (s ? fmtDate(s) + ", " + fmtTime(s) : "-");
export const ymd = (d) => new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 10);
export const nowHM = () => { const d = new Date(); return String(d.getHours()).padStart(2, "0") + ":" + String(d.getMinutes()).padStart(2, "0"); };
export const toMin = (hm) => { const [h, m] = hm.split(":").map(Number); return h * 60 + m; };
export const daysUntil = (s) => Math.ceil((new Date(s).getTime() - Date.now()) / 86400000);
export const monthsSince = (s) => Math.max(0, Math.round((Date.now() - new Date(s).getTime()) / (86400000 * 30)));
